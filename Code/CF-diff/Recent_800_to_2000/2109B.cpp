using namespace std;
typedef long long ll;
#define mod 1000000007
vector<bool> prime;
 
void sieve(ll n)
{
    prime.resize(n + 1, true);
    prime[0] = prime[1] = false;
    for (ll i = 2; i <= n; i++) {
        if (prime[i] && i * i <= n) {
            for (ll j = i * i; j <= n; j += i)
                prime[j] = false;
        }
    }
}
 
template<typename T>
std::istream& operator>>(std::istream&in, std::vector<T>& v) {
    for (T& x : v)
        in >> x;
    return in;
}
 
template<typename T>
std::ostream& operator<<(std::ostream&out, std::vector<T>& v) {
    for (const T& x : v)
        std::cout << x << ' ';
    std::cout << '\n';
    return out;
}

int calc(int a) {
    if (a == 1) {
        return 0;
    }
    return 1 + calc(a - a / 2);
}

int fun(int a, int b) {
    ll res = calc(a) + calc(b);
    return res;
}
 
void solve()
{   //19  mins too long
    int n, m, a, b;
    cin >> n >> m >> a >> b;
    cout << 1 + min({fun(n + 1 - a, m), fun(n, m - b + 1), fun(a, m), fun(n, b)});
}
 
